//! Pluggable doom-loop detection for streaming LLM generation.
//!
//! Each pathological generation pattern is recognized by a small detector
//! implementing the [`Detector`] trait. [`DoomloopPipeline`] is a list of
//! detectors with a dispatch loop — it holds no configuration of its own.
//! Per-detector parameters (including each detector's own `min_chars`
//! threshold) live on the detector structs.
//!
//! See `docs/pipette-doomloop/doomloop-detection.md` for the full discussion
//! of patterns, parameter rationale, and tuning notes.

mod block_repeat;
mod cyclic_line_repeat;
mod exact_repeat;
mod line_repeat;
mod numeric_enumeration;
mod suffix_probe;

#[cfg(feature = "plan")]
pub mod plan;

use std::fmt::Debug;

