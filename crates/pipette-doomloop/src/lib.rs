pub use suffix_probe::SuffixProbe;

/// Take the trailing `n` bytes of `bytes`, or the entire slice if shorter.
/// Every detector starts by slicing its scan tail with this helper.
pub(crate) fn tail_of(bytes: &[u8], n: usize) -> &[u8] {
    let start = bytes.len().saturating_sub(n);
    &bytes[start..]
}

/// Render the warning text emitted when a detector stops generation early.
///
/// Single source of truth for the wire format that `pipette-llamacpp` and
/// `pipette-mlx` write via `log::warn!`. The log line is the only
/// observable signal of a trigger — keep the format stable so anyone
/// grepping logs can rely on it.
pub fn format_trigger_log(detector: &str, at_bytes: usize) -> String {
    format!("doom loop detected by {detector} after {at_bytes} generated bytes, stopping early")
}

/// A single doom-loop detection strategy.
///
/// Consumers call `check` at natural checkpoints in their transport (every
/// 50 SSE chunks for `pipette-llamacpp`, every 256 generated bytes for
/// `pipette-mlx`) on the whole accumulated generation buffer. Each
/// implementation is responsible for its own `min_chars` gate — there is
/// no global one.
///
/// # Adding a detector
///
/// 1. Create a new module under `crates/pipette-doomloop/src/<name>.rs`.
/// 2. Define a `pub struct YourDetector` carrying the algorithm knobs plus
///    `pub min_chars: usize`. Derive `Debug, Clone, Default`.
/// 3. Implement [`Detector`] on the struct. `name()` must be a snake_case
///    `&'static str` with no whitespace — it appears verbatim in the
///    [`format_trigger_log`] output operators may grep. `check()` must
///    return `false` when `content.len() < self.min_chars` or when any knob
///    is in an invalid state (zeroed windows, thresholds below their
///    meaningful minimum).
/// 4. Re-export the struct from `lib.rs` and add `Box::new(YourDetector::default())`
///    to [`DoomloopPipeline::default`]. No dispatch code changes — the
///    pipeline's single loop handles any number of detectors automatically.
/// 5. Extend plan-form overrides (`plan` feature) and `to_pipeline` so a cell
///    can author the new knobs; keep `append_argv` in sync for remote spawn.
/// 6. Add matching `--doomloop-<name>-*` clap fields on
///    `pipette-cli`'s `DoomloopCliArgs` and map them in `into_overrides`.
/// 7. Add a row to the table in `docs/pipette-doomloop/doomloop-detection.md`
///    explaining what pattern the detector catches.
///
/// # Example
///
/// ```
/// use pipette_doomloop::{Detector, DoomloopPipeline};
///
/// /// Toy detector: fires when the content ends with three exclamation marks.
/// #[derive(Debug)]
/// struct ShoutDetector {
///     min_chars: usize,
/// }
///
/// impl Detector for ShoutDetector {
///     fn name(&self) -> &'static str { "shout" }
///     fn check(&self, content: &str) -> bool {
///         content.len() >= self.min_chars && content.ends_with("!!!")
///     }
/// }
///
/// let mut pipeline = DoomloopPipeline::default();
/// pipeline.detectors.push(Box::new(ShoutDetector { min_chars: 8 }));
///
/// assert_eq!(pipeline.check("hello!!!"), Some("shout"));
/// assert_eq!(pipeline.check("short"), None); // below shout's own min_chars
/// ```
pub trait Detector: Send + Sync + Debug {
    /// Snake-case identifier used in CLI flags and the "doom loop detected
    /// by …" log line.
    fn name(&self) -> &'static str;

    /// Returns `true` when the tail of `content` matches this detector's
    /// pattern. Implementations must return `false` when `content.len()` is
    /// below their `min_chars` or when any knob is invalid.
    fn check(&self, content: &str) -> bool;

    /// Describe any knob combination that would make `check` unconditionally
    /// return `false` (zeroed windows, `required < 2`, and so on). Default
    /// returns `Ok`; detectors that have structural constraints override
    /// this so misconfigured plans fail loudly at startup instead of
    /// silently no-opping per-check.
    fn validate(&self) -> Result<(), String> {
        Ok(())
    }
}

/// Dispatch pipeline: detectors are run in insertion order; the first to
/// fire wins and its [`Detector::name`] is returned.
#[derive(Debug)]
pub struct DoomloopPipeline {
    pub detectors: Vec<Box<dyn Detector>>,
}

impl Default for DoomloopPipeline {
    fn default() -> Self {
        Self {
            detectors: vec![
                Box::new(ExactRepeat::default()),
                Box::new(LineRepeat::default()),
                Box::new(CyclicLineRepeat::default()),
                Box::new(BlockRepeat::default()),
                Box::new(NumericEnumeration::default()),
                Box::new(SuffixProbe::default()),
            ],
        }
    }
}

impl DoomloopPipeline {
    /// An empty pipeline that never fires.
    pub fn disabled() -> Self {
        Self {
            detectors: Vec::new(),
        }
    }

    /// Returns the name of the first detector to fire on `content`, or `None`.
    pub fn check(&self, content: &str) -> Option<&'static str> {
        self.detectors
            .iter()
            .find_map(|d| d.check(content).then(|| d.name()))
    }

    /// Validate every detector in the pipeline; return the first error
    /// prefixed with the offending detector's name. Call this at binary
    /// startup so a misconfigured plan fails loudly instead of silently
    /// reducing `check` to a no-op.
    pub fn validate(&self) -> Result<(), String> {
        self.detectors
            .iter()
            .find_map(|d| d.validate().err().map(|e| format!("{}: {e}", d.name())))
            .map_or(Ok(()), Err)
    }
}

#[cfg(test)]
mod tests {
    use anyhow::Context;

    use super::*;

    #[test]
    fn tail_of_returns_full_slice_when_window_exceeds_input() {
        assert_eq!(tail_of(b"hello", 100), b"hello");
        assert_eq!(tail_of(b"hello world", 5), b"world");
        assert_eq!(tail_of(b"", 8), b"");
    }

    /// Operators grep this log line — drift would silently break their
    /// queries. Any wire-format change must update this assertion.
    #[test]
    fn format_trigger_log_pins_wire_format() {
        assert_eq!(
            format_trigger_log("exact_repeat", 4847),
            "doom loop detected by exact_repeat after 4847 generated bytes, stopping early"
        );
        assert_eq!(
            format_trigger_log("line_repeat", 0),
            "doom loop detected by line_repeat after 0 generated bytes, stopping early"
        );
    }

    /// A pipeline whose detectors all have `min_chars = 0`, so tests
    /// that verify firing *logic* don't have to produce fixtures
    /// larger than the default activation threshold.
    fn short_pipeline() -> DoomloopPipeline {
        DoomloopPipeline {
            detectors: vec![
                Box::new(ExactRepeat {
                    min_chars: 0,
                    ..Default::default()
                }),
                Box::new(LineRepeat {
                    min_chars: 0,
                    ..Default::default()
                }),
                Box::new(CyclicLineRepeat {
                    min_chars: 0,
                    ..Default::default()
                }),
                Box::new(BlockRepeat {
                    min_chars: 0,
                    ..Default::default()
                }),
                Box::new(NumericEnumeration {
                    min_chars: 0,
                    ..Default::default()
                }),
                Box::new(SuffixProbe {
                    min_chars: 0,
                    ..Default::default()
                }),
            ],
        }
    }

    #[test]
    fn default_pipeline_has_six_builtins_in_order() {
        let p = DoomloopPipeline::default();
        assert_eq!(p.detectors.len(), 6);
        assert_eq!(p.detectors[0].name(), "exact_repeat");
        assert_eq!(p.detectors[1].name(), "line_repeat");
        assert_eq!(p.detectors[2].name(), "cyclic_line_repeat");
        assert_eq!(p.detectors[3].name(), "block_repeat");
        assert_eq!(p.detectors[4].name(), "numeric_enumeration");
        assert_eq!(p.detectors[5].name(), "suffix_probe");
    }

    #[test]
    fn exact_repeat_fires_first() {
        let p = short_pipeline();
        let content = "the ".repeat(300);
        assert_eq!(p.check(&content), Some("exact_repeat"));
    }

    #[test]
    fn line_repeat_fires_when_exact_misses() {
        let p = short_pipeline();
        let content: String = (200..220)
            .map(|i| format!("    *   *Recipe {i}: Ethiopian Fried Chicken* (Classic side dish)\n"))
            .collect();
        assert_eq!(p.check(&content), Some("line_repeat"));
    }

    /// Real-log pattern from `2026.04.16-macos-windows.log` sample id=629:
    /// a numbered A,B,A,B checklist. SweepPins pipeline attribution to
    /// `cyclic_line_repeat` rather than any byte-level detector.
    #[test]
    fn cyclic_line_repeat_fires_on_alternating_checklist() {
        let p = short_pipeline();
        let content: String = (16..=27u32)
            .map(|i| {
                let body = if i.is_multiple_of(2) {
                    "No code block? Yes."
                } else {
                    "No object wrapper? Yes."
                };
                format!("            {i}. {body}\n")
            })
            .collect();
        assert_eq!(p.check(&content), Some("cyclic_line_repeat"));
    }

    #[test]
    fn block_repeat_fires_for_long_period_block() {
        let p = DoomloopPipeline::default();
        let mut block = String::new();
        block.push_str("```json\n{\n  \"type\": \"object\",\n  \"properties\": {\n");
        (0..22).for_each(|i| {
            block.push_str(&format!(
                "    \"field_{i:02}\": {{ \"type\": \"string\", \"description\": \"Schema field {i} with filler text padding.\" }},\n",
            ));
        });
        block.push_str("  }\n}\n```\n*Wait, looking at the schema again.*\n");
        let content = block.repeat(8);
        assert_eq!(p.check(&content), Some("block_repeat"));
    }

    #[test]
    fn suffix_probe_fires_for_short_tail_drift() {
        let p = short_pipeline();
        let body = " — and the values must be consistent with the schema requirements defined in the prompt.";
        let mut content = String::new();
        [
            "Wait, I need to check",
            "Actually, I will ensure",
            "Okay, I need to verify",
            "Now, I need to confirm",
            "Again, I will ensure",
        ]
        .iter()
        .for_each(|prefix| {
            content.push_str(prefix);
            content.push_str(body);
            content.push('\n');
        });
        assert_eq!(p.check(&content), Some("suffix_probe"));
    }

    #[test]
    fn returns_none_for_clean_text() {
        let p = DoomloopPipeline::default();
        let content = "The quick brown fox jumps over the lazy dog. \
                       Pack my box with five dozen liquor jugs. \
                       How vexingly quick daft zebras jump.";
        assert_eq!(p.check(content), None);
    }

    #[test]
    fn default_pipeline_validates() {
        assert!(DoomloopPipeline::default().validate().is_ok());
    }

    #[test]
    fn misconfigured_detector_surfaces_named_error() -> anyhow::Result<()> {
        let mut p = DoomloopPipeline {
            detectors: vec![Box::new(ExactRepeat {
                required: 1,
                ..ExactRepeat::default()
            })],
        };
        let err = p.validate().err().context("expected validation error")?;
        assert!(err.starts_with("exact_repeat: "), "got: {err}");
        // Fixing the offending knob clears the error.
        p.detectors.clear();
        p.detectors.push(Box::new(ExactRepeat::default()));
        assert!(p.validate().is_ok());
        Ok(())
    }

    #[test]
    fn disabled_pipeline_never_fires() {
        let p = DoomloopPipeline::disabled();
        let content = "the ".repeat(500);
        assert_eq!(p.check(&content), None);
    }

    #[derive(Debug)]
    struct AlwaysFires(&'static str);
    impl Detector for AlwaysFires {
        fn name(&self) -> &'static str {
            self.0
        }
        fn check(&self, _content: &str) -> bool {
            true
        }
    }

    #[test]
    fn pushing_a_detector_extends_dispatch() {
        let mut p = DoomloopPipeline::default();
        p.detectors.push(Box::new(AlwaysFires("custom")));
        // Clean prose so built-ins miss; the pushed detector then catches.
        let prose = "Padding for the min_chars gate: lorem ipsum dolor sit amet, \
                     consectetur adipiscing elit, sed do eiusmod tempor incididunt \
                     ut labore et dolore magna aliqua. Ut enim ad minim veniam, \
                     quis nostrud exercitation ullamco laboris nisi ut aliquip ex \
                     ea commodo consequat.";
        assert_eq!(p.check(prose), Some("custom"));
    }

    #[test]
    fn pushed_detector_runs_after_builtins() {
        // Content that trips a built-in — built-in wins because it's first.
        let mut p = short_pipeline();
        p.detectors.push(Box::new(AlwaysFires("custom")));
        let loop_content = "the ".repeat(300);
        assert_eq!(p.check(&loop_content), Some("exact_repeat"));
    }
}
