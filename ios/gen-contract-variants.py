#!/usr/bin/env python3
"""Render the contract as exhaustive Swift switches, one per mirrored enum.

Reads crates/pipette-contract/fixtures/variants.json (kept by that crate's `contract`
test) and ios/contract-refusals.json. `ModelType` and `RuntimeType` switch over
every variant, since a discriminant names every tag; each Swift enum named as the
crate's switches over its unrefused variants, unless only refused examples reach it.
So a variant either side lacks, or a refused one Swift keeps, fails to compile.

The output is committed because a synchronized folder compiles only files present
when the project opens; a PipetteTests build phase regenerates it, and
ci/checks/contract.py fails a PR whose copy is stale.

    gen-contract-variants.py <contract fixtures> <refusals.json> <out.swift>

Stdlib only and 3.9-compatible: Xcode runs it with the system python3.
"""

import json
import re
import sys
from pathlib import Path

# The crate's enum -> the Swift discriminant that names every one of its variants.
DISCRIMINANTS = {"Model": "ModelType", "Runtime": "RuntimeType"}

# Wire names whose Swift case is not their camel case.
CASE_NAMES = {
    "huggingface": "huggingFace",
    "mmspec@1": "mmspecV1",
    "vl-spec-decode-corpus/1": "vlSpecDecodeCorpusV1",
}

# The same, for a wire name that only one enum renames: a `none` case would be
# `Optional.none` wherever the value is optional.
ENUM_CASE_NAMES = {
    ("LlamacppLoadMode", "none"): "read",
}


def case_name(swift_enum: str, variant: str) -> str:
    if (swift_enum, variant) in ENUM_CASE_NAMES:
        return ENUM_CASE_NAMES[(swift_enum, variant)]
    if variant in CASE_NAMES:
        return CASE_NAMES[variant]
    head, *rest = re.split("[_-]", variant)
    return head + "".join(part[:1].upper() + part[1:] for part in rest)


def switch(swift_enum: str, variants: list) -> list:
    return [
        "",
        f"private func contract{swift_enum}(_ value: {swift_enum}) {{",
        "    switch value {",
        *(f"    case .{case_name(swift_enum, variant)}: break" for variant in variants),
        "    }",
        "}",
    ]


def render(variants: dict, refusals: dict) -> str:
    for enum, refused in refusals.items():
        stale = sorted(set(refused) - set(variants.get(enum, {})))
        if stale:
            lacks = ", ".join(stale)
            raise ValueError(f"refuses {enum} variants the contract lacks: {lacks}")
    refused_examples = {
        example
        for enum, refused in refusals.items()
        for variant in refused
        for example in variants[enum][variant]
    }
    lines = [
        "// Generated by ios/gen-contract-variants.py from the contract.",
        "",
        "@testable import Pipette",
    ]
    for enum, swift_enum in DISCRIMINANTS.items():
        lines += switch(swift_enum, sorted(variants[enum]))
    for enum, held in sorted(variants.items()):
        examples = {example for holding in held.values() for example in holding}
        if examples <= refused_examples:
            continue
        refused = refusals.get(enum, {})
        lines += switch(enum, sorted(v for v in held if v not in refused))
    return "\n".join(lines) + "\n"


def main() -> int:
    if len(sys.argv) != 4:
        print(
            "usage: gen-contract-variants.py"
            " <contract fixtures> <refusals.json> <out.swift>",
            file=sys.stderr,
        )
        return 2
    contract, refusals, out_path = (Path(arg) for arg in sys.argv[1:])
    try:
        rendered = render(
            json.loads((contract / "variants.json").read_text(encoding="utf-8")),
            json.loads(refusals.read_text(encoding="utf-8")),
        )
    except (OSError, KeyError, TypeError, ValueError) as err:
        # Xcode surfaces an `error:` line as a build error on the phase.
        print(f"error: contract {contract} or {refusals}: {err}", file=sys.stderr)
        return 1
    try:
        current = out_path.read_text(encoding="utf-8")
    except FileNotFoundError:
        current = None
    if current != rendered:
        out_path.write_text(rendered, encoding="utf-8")
        print(f"warning: regenerated {out_path} from the contract; commit it")
    return 0


if __name__ == "__main__":
    sys.exit(main())
