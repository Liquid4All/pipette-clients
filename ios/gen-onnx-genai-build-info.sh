#!/usr/bin/env bash
#
# Emit Generated/OnnxGenai/OnnxGenaiBuildInfo.swift and .json from the two
# vendored trees the in-process ONNX Runtime GenAI engine is built from. Both
# pins change what a measured number means, so the submitted runtime_descriptor
# names both.
#
# build-onnx-genai.sh runs this after each build, and CI runs it directly. The
# files are committed and rewritten only when their contents change, so an
# unchanged build does not force a recompile.
#
# Usage:
#   ./ios/gen-onnx-genai-build-info.sh

set -euo pipefail

if [[ "${1:-}" == "-h" || "${1:-}" == "--help" ]]; then
    sed -n '2,23s/^# \{0,1\}//p' "$0"
    exit 0
fi

REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT_DIR="$REPO_ROOT/ios/Pipette/Pipette/Generated/OnnxGenai"
OUT="$OUT_DIR/OnnxGenaiBuildInfo.swift"
OUT_JSON="$OUT_DIR/OnnxGenaiBuildInfo.json"

# `--recursive` because onnxruntime has nested submodules. The marker is a file
# only a real checkout carries.
require_submodule() {
    local path="$1" marker="$2"
    if [[ ! -f "$REPO_ROOT/$path/$marker" ]] \
       || git -C "$REPO_ROOT" submodule status --recursive "$path" | grep -q '^-'; then
        echo "==> initializing the vendored $path submodule"
        git -C "$REPO_ROOT" submodule update --init --recursive "$path" || true
    fi
    if [[ ! -f "$REPO_ROOT/$path/$marker" ]]; then
        echo "error: vendored sources missing at $path" >&2
        echo "       run: git submodule update --init --recursive $path" >&2
        exit 1
    fi
}

require_submodule vendor/onnxruntime VERSION_NUMBER
require_submodule vendor/onnxruntime-genai VERSION_INFO

# `--short=9`, not bare `--short`, for the reason build-llama.sh gives: the auto
# length differs between a dev machine and a fresh CI checkout.
short_commit() { git -C "$REPO_ROOT/$1" rev-parse --short=9 HEAD; }

# The `vN.N.N` release tag on this exact commit. Not `git describe`, which
# reports the nearest tag and would label a commit past v1.26.0 as v1.26.0.
#
# A shallow submodule clone (the CI checkout) has no tag objects, so the
# fallback is `vendor/<name>.tag`, as `<tag> <full-sha>` like vendor/llama.cpp.tag.
# A sha that no longer matches the pin rejects the recorded tag.
release_tag() {
    local path="$1" tag tag_file recorded_tag recorded_sha head_sha
    tag="$(git -C "$REPO_ROOT/$path" tag --points-at HEAD 2>/dev/null \
        | grep -E '^v[0-9]+\.[0-9]+\.[0-9]+$' | head -1 || true)"
    tag_file="$REPO_ROOT/$path.tag"
    if [[ -z "$tag" && -f "$tag_file" ]]; then
        read -r recorded_tag recorded_sha _ < "$tag_file" || true
        head_sha="$(git -C "$REPO_ROOT/$path" rev-parse HEAD)"
        if [[ ! "${recorded_tag:-}" =~ ^v[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
            echo "warning: $tag_file: '${recorded_tag:-}' is not a tag (vN.N.N) — ignoring" >&2
        elif [[ "${recorded_sha:-}" != "$head_sha" ]]; then
            echo "warning: $tag_file records ${recorded_tag} at ${recorded_sha:-<none>}, but the" >&2
            echo "         submodule is at ${head_sha} — update it when bumping the pin. Reporting untagged." >&2
        else
            tag="$recorded_tag"
        fi
    fi
    echo "$tag"
}

# The plan-types `RepositoryUrl` form, `<host>/<org>/<repo>`. Literals rather
# than `git remote get-url`: a submodule cloned through a mirror reports the
# mirror, and the descriptor must name the upstream repository.
ORT_URL="github.com/microsoft/onnxruntime"
GENAI_URL="github.com/microsoft/onnxruntime-genai"

ORT_COMMIT="$(short_commit vendor/onnxruntime)"
ORT_TAG="$(release_tag vendor/onnxruntime)"
GENAI_COMMIT="$(short_commit vendor/onnxruntime-genai)"
GENAI_TAG="$(release_tag vendor/onnxruntime-genai)"

# `Build.tagged` / `Build.untagged`, spelled as a Swift expression.
build_expr() {
    local tag="$1" commit="$2"
    if [[ -n "$tag" ]]; then
        echo "Build.tagged(tag: \"$tag\", commit: \"$commit\")"
    else
        echo "Build.untagged(commit: \"$commit\")"
    fi
}

content="// Generated by ios/gen-onnx-genai-build-info.sh — do not edit.
// What the in-process ONNX Runtime GenAI engine was built from: the two source
// trees, each as a pin and the upstream repository it came from.
// nonisolated so the nonisolated OnnxGenaiRuntime can read it off the main actor.
nonisolated enum OnnxGenaiBuildInfo {
    /// A release tag names a pin that a plan can also name; a cherry-picked fix
    /// leaves nothing to tag it with, so \`untagged\` is a real state.
    nonisolated enum Build {
        case tagged(tag: String, commit: String)
        case untagged(commit: String)

        /// Always present, and the exact identity: a tag can be moved or deleted
        /// upstream, a commit cannot.
        var commit: String {
            switch self {
            case let .tagged(_, commit), let .untagged(commit):
                return commit
            }
        }

        /// The upstream git tag on this pin, when it carries one.
        var tag: String? {
            switch self {
            case let .tagged(tag, _): return tag
            case .untagged: return nil
            }
        }

        /// What a submission reports as \`repository_version\`: the tag when the
        /// pin has one, so the descriptor names the release a plan pins by, and
        /// the commit otherwise, which is still exact.
        var submissionVersion: String { tag ?? commit }
    }

    static let onnxruntime = $(build_expr "$ORT_TAG" "$ORT_COMMIT")
    static let onnxruntimeGenai = $(build_expr "$GENAI_TAG" "$GENAI_COMMIT")

    static let onnxruntimeRepositoryUrl = \"$ORT_URL\"
    static let onnxruntimeGenaiRepositoryUrl = \"$GENAI_URL\"
}
"

# One pin as a JSON member; an untagged pin's tag is `null`.
json_pin() {
    local name="$1" url="$2" tag="$3" commit="$4" tag_json=null
    [[ -n "$tag" ]] && tag_json="\"$tag\""
    printf '  "%s": {"repository_url": "%s", "tag": %s, "commit": "%s"}' \
        "$name" "$url" "$tag_json" "$commit"
}

# The same values as data, for ios/release-manifest.py. Kept out of the app
# bundle by a membership exception in the project.
json="{
$(json_pin onnxruntime "$ORT_URL" "$ORT_TAG" "$ORT_COMMIT"),
$(json_pin onnxruntime_genai "$GENAI_URL" "$GENAI_TAG" "$GENAI_COMMIT")
}
"

# Rewrite only on change so an unchanged build does not bump mtime / recompile.
write_if_changed() {
    local path="$1" body="$2"
    if [[ -f "$path" && "$(cat "$path")" == "$(printf '%s' "$body")" ]]; then
        echo "==> ${path##*/} up to date"
        return
    fi
    mkdir -p "$OUT_DIR"
    printf '%s' "$body" > "$path"
    echo "==> Wrote ${path##*/} (onnxruntime=${ORT_TAG:-$ORT_COMMIT} onnxruntime-genai=${GENAI_TAG:-$GENAI_COMMIT})"
}

write_if_changed "$OUT" "$content"
write_if_changed "$OUT_JSON" "$json"
