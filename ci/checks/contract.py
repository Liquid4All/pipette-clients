#!/usr/bin/env python3
"""Fail when the committed Swift switches over the contract are stale.

`PipetteTests/Generated/ContractVariants.swift` is regenerated by an Xcode
build phase, but committed because a synchronized folder compiles only files
that exist when the project opens; this keeps the committed copy current.
"""

import subprocess
import sys
import tempfile
from pathlib import Path

CONTRACT = Path("crates/pipette-contract/fixtures")
REFUSALS = Path("ios/contract-refusals.json")
GENERATOR = Path("ios/gen-contract-variants.py")
GENERATED = Path("ios/Pipette/PipetteTests/Generated/ContractVariants.swift")


def main() -> int:
    with tempfile.TemporaryDirectory() as tmp:
        fresh = Path(tmp) / GENERATED.name
        subprocess.run(
            [sys.executable, str(GENERATOR), str(CONTRACT), str(REFUSALS), str(fresh)],
            check=True,
            stdout=subprocess.DEVNULL,
        )
        committed = (
            GENERATED.read_text(encoding="utf-8") if GENERATED.exists() else None
        )
        if fresh.read_text(encoding="utf-8") != committed:
            print(
                f"{GENERATED}: stale; regenerate it with "
                f"`{GENERATOR} {CONTRACT} {REFUSALS} {GENERATED}` and commit it"
            )
            return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
